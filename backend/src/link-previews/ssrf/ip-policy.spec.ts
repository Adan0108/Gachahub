import { isPublicAddress } from './ip-policy';

describe('isPublicAddress', () => {
  it.each([
    ['8.8.8.8'],
    ['1.1.1.1'],
    ['93.184.216.34'],
    ['172.15.255.255'],
    ['172.32.0.1'],
    ['100.63.255.255'],
    ['100.128.0.1'],
    ['2606:4700:4700::1111'],
    ['2a00:1450:4001:81b::200e'],
  ])('allows the public address %s', (address) => {
    expect(isPublicAddress(address)).toBe(true);
  });

  it.each([
    ['0.0.0.0'],
    ['0.1.2.3'],
    ['10.0.0.1'],
    ['10.255.255.255'],
    ['100.64.0.1'],
    ['100.127.255.255'],
    ['127.0.0.1'],
    ['127.255.255.254'],
    ['169.254.169.254'],
    ['169.254.0.1'],
    ['172.16.0.1'],
    ['172.31.255.255'],
    ['192.0.0.1'],
    ['192.0.2.1'],
    ['192.168.0.1'],
    ['192.168.255.255'],
    ['198.18.0.1'],
    ['198.19.255.255'],
    ['198.51.100.1'],
    ['203.0.113.1'],
    ['224.0.0.1'],
    ['239.255.255.255'],
    ['240.0.0.1'],
    ['255.255.255.255'],
  ])('refuses the reserved IPv4 address %s', (address) => {
    expect(isPublicAddress(address)).toBe(false);
  });

  it.each([
    ['::'],
    ['::1'],
    ['::ffff:127.0.0.1'],
    ['::ffff:7f00:1'],
    ['::ffff:10.0.0.1'],
    ['::ffff:8.8.8.8'],
    ['::127.0.0.1'],
    ['64:ff9b::7f00:1'],
    ['64:ff9b:1::1'],
    ['100::1'],
    ['2001::1'],
    ['2001:db8::1'],
    ['2002:7f00:1::1'],
    ['fc00::1'],
    ['fd12:3456:789a::1'],
    ['fe80::1'],
    ['febf::1'],
    ['fec0::1'],
    ['ff02::1'],
  ])('refuses the reserved IPv6 address %s', (address) => {
    expect(isPublicAddress(address)).toBe(false);
  });

  it.each([
    [''],
    ['example.com'],
    ['999.1.1.1'],
    ['1.2.3'],
    ['8.8.8.8:80'],
    ['fe80::1%eth0'],
    ['2606:4700:4700::1111%1'],
    ['0x7f.0.0.1'],
    ['2130706433'],
  ])('refuses %p, which is not a plain IP literal', (value) => {
    expect(isPublicAddress(value)).toBe(false);
  });
});
